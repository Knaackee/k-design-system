import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import {
  Worker,
  isMainThread,
  parentPort,
  workerData,
} from "node:worker_threads";
import { Resvg } from "@resvg/resvg-js";

if (!isMainThread) {
  const raster = {};
  for (const item of workerData) {
    for (const variant of [item, ...item.tones]) {
      raster[variant.value] = new Resvg(variant.svg, {
        fitTo: { mode: "width", value: 72 },
      })
        .render()
        .asPng()
        .toString("base64");
    }
  }
  parentPort.postMessage(raster);
} else {
  const root = new URL("../", import.meta.url);
  const source = await readFile(new URL("assets/emoji/catalog.json", root));
  const digest = createHash("sha256")
    .update(source)
    .update("resvg@2.6.2;width72")
    .digest("hex");
  const file =
    "packages/flutter/k_design_ui/lib/src/generated/k_emoji_rasters.g.dart";
  const target = new URL(file, root);
  if (process.argv.includes("--check")) {
    const content = await readFile(target, "utf8").catch(() => "");
    const lines = content.split("\n");
    const body = lines.slice(2).join("\n");
    const bodyDigest = createHash("sha256").update(body).digest("hex");
    if (
      lines[0] !== `// source-sha256: ${digest}` ||
      lines[1] !== `// body-sha256: ${bodyDigest}`
    )
      throw new Error(`Emoji raster drift: ${file}`);
    console.log("Verified emoji raster source digest.");
  } else {
    const entries = JSON.parse(source.toString("utf8"));
    const workers = 6;
    const chunks = Array.from({ length: workers }, () => []);
    entries.forEach((entry, index) => chunks[index % workers].push(entry));
    const results = await Promise.all(
      chunks.map(
        (chunk) =>
          new Promise((resolve, reject) => {
            const worker = new Worker(new URL(import.meta.url), {
              workerData: chunk,
            });
            worker.once("message", resolve);
            worker.once("error", reject);
            worker.once("exit", (code) => {
              if (code !== 0) reject(new Error(`Raster worker exited ${code}`));
            });
          }),
      ),
    );
    const raster = Object.assign({}, ...results);
    const body = `// Generated by tooling/rasterize-emoji.mjs; do not edit.\nconst kEmojiRasters = <String, String>${JSON.stringify(raster)};\n`;
    const bodyDigest = createHash("sha256").update(body).digest("hex");
    const content = `// source-sha256: ${digest}\n// body-sha256: ${bodyDigest}\n${body}`;
    await writeFile(target, content);
    console.log(`Verified ${Object.keys(raster).length} emoji rasters.`);
  }
}
