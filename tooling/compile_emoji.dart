import 'dart:convert';
import 'dart:io';
import 'package:vector_graphics_compiler/vector_graphics_compiler.dart';

// Compile at generation time, never on the user's first picker interaction.
void main(List<String> args) {
  final root = File.fromUri(Platform.script).parent.parent.path;
  final items =
      jsonDecode(File('$root/assets/emoji/catalog.json').readAsStringSync())
          as List;
  final vectors = <String, String>{};
  for (final item in items) {
    for (final variant in [item, ...item['tones'] as List]) {
      final bytes = encodeSvg(
        xml: variant['svg'] as String,
        debugName: variant['value'] as String,
        enableClippingOptimizer: false,
        enableMaskingOptimizer: false,
        enableOverdrawOptimizer: false,
      );
      vectors[variant['value'] as String] = base64Encode(bytes);
    }
  }
  final content =
      '// Generated by tooling/compile_emoji.dart; do not edit.\n'
      'const kEmojiVectors = <String, String>${jsonEncode(vectors)};\n';
  final output = File(
    '$root/packages/flutter/k_design_ui/lib/src/generated/k_emoji_vectors.g.dart',
  );
  if (args.contains('--check')) {
    if (!output.existsSync() || output.readAsStringSync() != content) {
      throw StateError('Compiled emoji catalog drift');
    }
  } else {
    output.writeAsStringSync(content);
  }
  stdout.writeln('Verified ${vectors.length} compiled emoji vectors.');
}
