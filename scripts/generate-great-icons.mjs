import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const assets = new URL("assets/icons/great-icons/", root);
const catalog = JSON.parse(
  await readFile(new URL("catalog.json", assets), "utf8"),
);
const images = {};
for (const [key, filename] of Object.entries(catalog.icons)) {
  const bytes = await readFile(new URL(filename, assets));
  const mime = filename.endsWith(".svg") ? "image/svg+xml" : "image/png";
  images[key] = `data:${mime};base64,${bytes.toString("base64")}`;
}
await writeFile(
  new URL("packages/web/ui/src/generated/great-icons.ts", root),
  `// Generated by scripts/generate-great-icons.mjs. MIT; see assets/icons/great-icons/LICENSE.\n` +
    `export const greatIconImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n` +
    `export const greatIconExtensions: Record<string, string> = ${JSON.stringify(catalog.extensions, null, 2)};\n`,
);
