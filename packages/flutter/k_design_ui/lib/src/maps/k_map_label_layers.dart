List<Object> _poiColor(KMapTokens tokens) => [
  'match',
  ['get', 'class'],
  for (final entry in _poiGroups.entries) ...[entry.value, tokens[entry.key]],
  tokens.poiOther,
];

List<Map<String, Object>> buildLabelLayers(
  KMapTokens tokens,
  KMapSettings settings,
) {
  final name = nameField(settings.lang);
  final halo = <String, Object>{
    'text-halo-color': tokens.labelHalo,
    'text-halo-width': settings.haloWidth,
    'text-halo-blur': 0.3,
  };
  List<Object> textSize(Stops stops) =>
      zlin(scaleStops(stops, settings.labelScale));
  double textConstant(num value) => rounded(value * settings.labelScale, 2);

  return [
    {
      'id': 'label-water',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'water_name',
      'filter': isPoint,
      'layout': {
        'text-field': name,
        'text-font': tokens.fontItalic,
        'text-size': textSize([(8, 11), (14, 13)]),
        'text-max-width': 6,
      },
      'paint': {'text-color': tokens.waterLabel, ...halo},
    },
    {
      'id': 'label-waterway',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'waterway',
      'minzoom': 13,
      'filter': [
        'all',
        isLine,
        byClass(['river', 'canal']),
      ],
      'layout': {
        'text-field': name,
        'text-font': tokens.fontItalic,
        'text-size': textConstant(12),
        'symbol-placement': 'line',
        'symbol-spacing': 500,
        'text-letter-spacing': 0.05,
      },
      'paint': {'text-color': tokens.waterLabel, ...halo},
    },
    {
      'id': 'label-road-minor',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'transportation_name',
      'minzoom': settings.roadLabelMinZoom + 2,
      'filter': [
        'all',
        isLine,
        byClass(['minor', 'service']),
      ],
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-size': textSize([(15, 10), (18, 12.5)]),
        'symbol-placement': 'line',
        'symbol-spacing': 400,
        'text-max-angle': 30,
        'text-padding': 4,
      },
      'paint': {'text-color': tokens.labelSubtle, ...halo},
    },
    {
      'id': 'label-road-major',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'transportation_name',
      'minzoom': settings.roadLabelMinZoom,
      'filter': [
        'all',
        isLine,
        byClass(['primary', 'secondary', 'tertiary', 'trunk']),
      ],
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-size': textSize([(13, 10.5), (17, 13)]),
        'symbol-placement': 'line',
        'symbol-spacing': 400,
        'text-max-angle': 30,
        'text-padding': 4,
      },
      'paint': {'text-color': tokens.label, ...halo},
    },
    {
      'id': 'poi-dot',
      'type': 'circle',
      'source': kMapSourceId,
      'source-layer': 'poi',
      'minzoom': settings.poiMinZoom,
      'filter': [
        'all',
        isPoint,
        [
          '<=',
          ['get', 'rank'],
          settings.poiMaxRank,
        ],
      ],
      'layout': visibility(settings.showPois),
      'paint': {
        'circle-color': _poiColor(tokens),
        'circle-radius': zlin(
          scaleStops([(15, 3.5), (18, 5.5)], settings.poiDotScale),
        ),
        'circle-stroke-color': tokens.poiStroke,
        'circle-stroke-width': 1.5,
      },
    },
    {
      'id': 'poi-label',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'poi',
      'minzoom': settings.poiMinZoom,
      'filter': [
        'all',
        isPoint,
        [
          '<=',
          ['get', 'rank'],
          settings.poiMaxRank,
        ],
        ['has', 'name'],
      ],
      'layout': {
        ...visibility(settings.showPois),
        'text-field': name,
        'text-font': tokens.fontBold,
        'text-size': textConstant(11.5),
        'text-max-width': 8,
        'text-variable-anchor': ['left', 'right'],
        'text-radial-offset': 0.8,
        'text-justify': 'auto',
        'symbol-sort-key': ['get', 'rank'],
        'text-padding': 6,
      },
      'paint': {'text-color': _poiColor(tokens), ...halo},
    },
    {
      'id': 'label-quarter',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'minzoom': 12,
      'filter': byClass(['suburb', 'quarter', 'neighbourhood']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-transform': 'uppercase',
        'text-letter-spacing': 0.12,
        'text-size': textSize([(12, 10), (15, 11.5)]),
        'text-max-width': 8,
        ...visibility(settings.showQuarterLabels),
      },
      'paint': {'text-color': tokens.labelSubtle, ...halo},
    },
    {
      'id': 'label-village',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'minzoom': 10,
      'filter': byClass(['village', 'hamlet']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-size': textSize([(10, 10.5), (14, 13)]),
        'text-max-width': 8,
      },
      'paint': {'text-color': tokens.label, ...halo},
    },
    {
      'id': 'label-town',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'minzoom': 7,
      'filter': byClass(['town']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-size': textSize([(7, 11), (12, 15)]),
        'text-max-width': 8,
      },
      'paint': {'text-color': tokens.labelStrong, ...halo},
    },
    {
      'id': 'label-city',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'minzoom': 3,
      'maxzoom': 16,
      'filter': byClass(['city']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontBold,
        'text-size': textSize([(4, 11), (8, 15), (13, 22)]),
        'text-max-width': 8,
        'symbol-sort-key': ['get', 'rank'],
      },
      'paint': {'text-color': tokens.labelStrong, ...halo},
    },
    {
      'id': 'label-state',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'minzoom': 5,
      'maxzoom': 8,
      'filter': byClass(['state']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontRegular,
        'text-transform': 'uppercase',
        'text-letter-spacing': 0.15,
        'text-size': textConstant(11),
        'text-max-width': 8,
      },
      'paint': {'text-color': tokens.labelSubtle, ...halo},
    },
    {
      'id': 'label-country',
      'type': 'symbol',
      'source': kMapSourceId,
      'source-layer': 'place',
      'maxzoom': 9,
      'filter': byClass(['country']),
      'layout': {
        'text-field': name,
        'text-font': tokens.fontBold,
        'text-size': textSize([(2, 11), (6, 15)]),
        'text-max-width': 8,
      },
      'paint': {'text-color': tokens.labelStrong, ...halo},
    },
  ];
}
