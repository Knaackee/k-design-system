    'restaurant',
    'fast_food',
    'cafe',
    'bar',
    'beer',
    'ice_cream',
    'bakery',
  ],
  'poiShop': [
    'shop',
    'grocery',
    'clothing_store',
    'alcohol_shop',
    'jewelry',
    'furniture',
    'hardware',
    'mobile_phone',
    'florist',
    'gift',
    'shoe',
    'music',
    'car',
    'bicycle',
    'electronics',
    'optician',
  ],
  'poiHealth': ['hospital', 'doctors', 'pharmacy', 'dentist', 'veterinary'],
  'poiEducation': ['school', 'college', 'library', 'kindergarten'],
  'poiLeisure': [
